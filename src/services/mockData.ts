// Helper to compute dynamic ISO date strings relative to the current evaluation date
function daysAgo(days: number, timeStr = '12:00:00Z'): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  const datePart = d.toISOString().split('T')[0];
  return `${datePart}T${timeStr}`;
}

function daysAgoDateOnly(days: number): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  return d.toISOString().split('T')[0];
}

